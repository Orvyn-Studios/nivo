//! Read-only WinEvents observation. No input hooks, injection, polling or window
//! activation. SetWinEventHook callbacks only coalesce work onto our own thread.
//!
//! Contracts and ownership follow Microsoft's documentation:
//! https://learn.microsoft.com/windows/win32/api/winuser/nf-winuser-setwineventhook
//! https://learn.microsoft.com/windows/win32/api/winuser/nf-winuser-unhookwinevent
//! https://learn.microsoft.com/windows/win32/api/winuser/nf-winuser-getwindowrect

use crate::fullscreen::{classify, FullscreenObservation, PhysicalRect, WindowGeometry};
use std::{
    cell::RefCell,
    mem::{size_of, zeroed},
    ptr,
    sync::{Arc, Mutex},
    thread::{self, JoinHandle},
};
use windows_sys::Win32::{
    Foundation::{GetLastError, SetLastError, HWND, RECT},
    Graphics::{
        Dwm::{DwmGetWindowAttribute, DWMWA_CLOAKED, DWMWA_EXTENDED_FRAME_BOUNDS},
        Gdi::{GetMonitorInfoW, MonitorFromWindow, MONITORINFO, MONITOR_DEFAULTTONEAREST},
    },
    System::Threading::GetCurrentThreadId,
    UI::{
        Accessibility::{SetWinEventHook, UnhookWinEvent, HWINEVENTHOOK},
        HiDpi::{SetThreadDpiAwarenessContext, DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2},
        WindowsAndMessaging::{
            DispatchMessageW, GetClassNameW, GetDesktopWindow, GetForegroundWindow, GetMessageW,
            GetShellWindow, GetWindowLongPtrW, GetWindowRect, GetWindowThreadProcessId, IsIconic,
            IsWindowVisible, IsZoomed, PeekMessageW, PostThreadMessageW, TranslateMessage,
            CHILDID_SELF, EVENT_OBJECT_LOCATIONCHANGE, EVENT_SYSTEM_FOREGROUND, GWL_STYLE, MSG,
            OBJID_WINDOW, PM_NOREMOVE, WINEVENT_OUTOFCONTEXT, WINEVENT_SKIPOWNPROCESS, WM_APP,
            WM_QUIT, WS_CAPTION, WS_THICKFRAME,
        },
    },
};

const REFRESH_MESSAGE: u32 = WM_APP + 41;

#[derive(Default)]
struct Lifecycle {
    thread_id: u32,
    stopping: bool,
    pending: bool,
    force: bool,
}

#[derive(Default)]
struct Control(Mutex<Lifecycle>);

impl Control {
    fn refresh(&self, force: bool) {
        let mut state = self.0.lock().unwrap_or_else(|error| error.into_inner());
        if state.stopping || state.thread_id == 0 {
            return;
        }
        state.force |= force;
        if state.pending {
            return;
        }
        // SAFETY: this ID is published only after our worker creates its queue,
        // and is cleared under this same lock before its thread can terminate.
        if unsafe { PostThreadMessageW(state.thread_id, REFRESH_MESSAGE, 0, 0) } != 0 {
            state.pending = true;
        }
    }
}

thread_local! {
    static EVENT_CONTROL: RefCell<Option<Arc<Control>>> = const { RefCell::new(None) };
}

/// Keep this guard alive for the application's lifetime. The callback runs on
/// a dedicated worker and must only enqueue/apply bounded work, never wait for
/// the main UI thread. Repeated WinEvent observations are deduplicated; explicit
/// refresh requests also retry UI reconciliation. `None` means an
/// API failed or there is no reliable foreground observation, not "uncovered".
/// Hook/DPI setup failures report `None` and stop the worker. Thread creation
/// failures are returned synchronously. Drop joins after posting WM_QUIT.
pub struct FullscreenObserver {
    control: Arc<Control>,
    worker: Option<JoinHandle<()>>,
}

impl FullscreenObserver {
    pub fn start(
        callback: impl FnMut(Option<FullscreenObservation>) + Send + 'static,
    ) -> Result<Self, String> {
        let control = Arc::new(Control::default());
        let worker_control = Arc::clone(&control);
        let worker = thread::Builder::new()
            .name("nivo-foreground".into())
            .spawn(move || observe(worker_control, callback))
            .map_err(|error| {
                format!("No se pudo iniciar el observador de pantalla completa: {error}")
            })?;
        Ok(Self {
            control,
            worker: Some(worker),
        })
    }

    /// Reconcile after Nivo's own focus changes, resume or display/preferences
    /// updates. SKIPOWNPROCESS intentionally excludes events generated by Nivo;
    /// the initial snapshot still observes an already-running foreground app.
    pub fn refresh(&self) {
        // Explicit adapter reconciliation also retries a previously failed UI
        // application, even when the foreground geometry has not changed.
        self.control.refresh(true);
    }
}

impl Drop for FullscreenObserver {
    fn drop(&mut self) {
        {
            let mut state = self
                .control
                .0
                .lock()
                .unwrap_or_else(|error| error.into_inner());
            state.stopping = true;
            if state.thread_id != 0 {
                // SAFETY: an owned worker ID with an initialized queue, protected
                // against exit/ID reuse by the lifecycle lock. No other app is
                // messaged. Its next loop iteration also checks stopping.
                unsafe { PostThreadMessageW(state.thread_id, WM_QUIT, 0, 0) };
            }
        }
        if let Some(worker) = self.worker.take() {
            // A callback may release the last owner. It must never join itself.
            if worker.thread().id() != thread::current().id() && worker.join().is_err() {
                eprintln!("El observador de pantalla completa terminó inesperadamente.");
            }
        }
    }
}

struct ThreadRegistration {
    control: Arc<Control>,
}

impl Drop for ThreadRegistration {
    fn drop(&mut self) {
        EVENT_CONTROL.with(|slot| *slot.borrow_mut() = None);
        let mut state = self
            .control
            .0
            .lock()
            .unwrap_or_else(|error| error.into_inner());
        state.thread_id = 0;
        state.pending = false;
    }
}

struct EventHook(HWINEVENTHOOK);

impl EventHook {
    fn install(event: u32) -> Option<Self> {
        // SAFETY: our process-local static callback is registered out-of-context.
        // No module is loaded into a foreign process; only the exact event is
        // requested, excluding our own process. This worker pumps its messages.
        let hook = unsafe {
            SetWinEventHook(
                event,
                event,
                ptr::null_mut(),
                Some(win_event),
                0,
                0,
                WINEVENT_OUTOFCONTEXT | WINEVENT_SKIPOWNPROCESS,
            )
        };
        if hook.is_null() {
            None
        } else {
            Some(Self(hook))
        }
    }
}

impl Drop for EventHook {
    fn drop(&mut self) {
        // SAFETY: this owning guard is created/dropped on the installing worker,
        // as UnhookWinEvent requires. It is neither cloned nor moved elsewhere.
        if unsafe { UnhookWinEvent(self.0) } == 0 {
            eprintln!("No se pudo retirar un observador WinEvent; su hilo está cerrando.");
        }
    }
}

unsafe extern "system" fn win_event(
    _: HWINEVENTHOOK,
    event: u32,
    hwnd: HWND,
    object: i32,
    child: i32,
    _: u32,
    _: u32,
) {
    let relevant = event == EVENT_SYSTEM_FOREGROUND
        || (event == EVENT_OBJECT_LOCATIONCHANGE
            && object == OBJID_WINDOW
            && child == CHILDID_SELF as i32
            && !hwnd.is_null()
            // SAFETY: a read-only foreground handle query; hwnd is compared only.
            && hwnd == unsafe { GetForegroundWindow() });
    if relevant {
        // Out-of-context callbacks run on the registering thread. No callback
        // executes user code, reads metadata or grows an application queue.
        let _ = EVENT_CONTROL.try_with(|slot| {
            if let Ok(control) = slot.try_borrow() {
                if let Some(control) = control.as_ref() {
                    control.refresh(false);
                }
            }
        });
    }
}

fn observe(control: Arc<Control>, mut callback: impl FnMut(Option<FullscreenObservation>)) {
    // SAFETY: a zeroed MSG is a valid output buffer. PeekMessage initializes the
    // thread queue before its ID is made visible to refresh()/Drop.
    let mut message: MSG = unsafe { zeroed() };
    unsafe { PeekMessageW(&mut message, ptr::null_mut(), 0, 0, PM_NOREMOVE) };
    {
        let mut state = control.0.lock().unwrap_or_else(|error| error.into_inner());
        if state.stopping {
            return;
        }
        state.thread_id = unsafe { GetCurrentThreadId() };
    }
    let _registration = ThreadRegistration {
        control: Arc::clone(&control),
    };
    EVENT_CONTROL.with(|slot| *slot.borrow_mut() = Some(Arc::clone(&control)));
    // GetWindowRect is DPI-virtualized but DWM bounds are not. This dedicated
    // worker uses physical coordinates without changing the UI/process context.
    let previous_dpi =
        unsafe { SetThreadDpiAwarenessContext(DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2) };
    if previous_dpi.is_null() {
        callback(None);
        return;
    }
    let Some(_foreground) = EventHook::install(EVENT_SYSTEM_FOREGROUND) else {
        callback(None);
        return;
    };
    let Some(_location) = EventHook::install(EVENT_OBJECT_LOCATIONCHANGE) else {
        callback(None);
        return;
    };
    let mut previous = current_observation();
    callback(previous);
    loop {
        if control
            .0
            .lock()
            .unwrap_or_else(|error| error.into_inner())
            .stopping
        {
            break;
        }
        // SAFETY: this worker owns its queue and does not create windows or enter
        // modal loops. GetMessage sleeps when idle and dispatches WinEvents here.
        let result = unsafe { GetMessageW(&mut message, ptr::null_mut(), 0, 0) };
        if result <= 0 {
            if result == -1 && previous.is_some() {
                callback(None);
            }
            break;
        }
        if message.message == REFRESH_MESSAGE {
            let force = {
                let mut state = control.0.lock().unwrap_or_else(|error| error.into_inner());
                state.pending = false;
                std::mem::take(&mut state.force)
            };
            let current = current_observation();
            if force || current != previous {
                previous = current;
                callback(current);
            }
        } else {
            unsafe {
                TranslateMessage(&message);
                DispatchMessageW(&message);
            }
        }
    }
    // This thread exits immediately after its owned hooks/registration drop, so
    // its DPI context cannot escape into any UI or unrelated worker operation.
}

fn physical(rect: RECT) -> PhysicalRect {
    PhysicalRect {
        left: rect.left,
        top: rect.top,
        right: rect.right,
        bottom: rect.bottom,
    }
}

fn is_shell_class(hwnd: HWND) -> Option<bool> {
    let mut buffer = [0_u16; 64];
    // SAFETY: bounded class-name query; no title/content is read or retained.
    let count = unsafe { GetClassNameW(hwnd, buffer.as_mut_ptr(), buffer.len() as i32) };
    if count == 0 {
        return None;
    }
    let class = &buffer[..count as usize];
    Some(
        [
            "Progman",
            "WorkerW",
            "Shell_TrayWnd",
            "Shell_SecondaryTrayWnd",
        ]
        .iter()
        .any(|candidate| class.iter().copied().eq(candidate.encode_utf16())),
    )
}

fn current_observation() -> Option<FullscreenObservation> {
    // SAFETY: all APIs below query OS-owned live handles without retaining them,
    // opening processes, reading titles or sending messages to another app.
    unsafe {
        let hwnd = GetForegroundWindow();
        if hwnd.is_null() {
            return None;
        }
        let monitor = MonitorFromWindow(hwnd, MONITOR_DEFAULTTONEAREST);
        let mut info: MONITORINFO = zeroed();
        info.cbSize = size_of::<MONITORINFO>() as u32;
        if monitor.is_null() || GetMonitorInfoW(monitor, &mut info) == 0 {
            return None;
        }
        let monitor_rect = physical(info.rcMonitor);
        if !monitor_rect.is_valid() {
            return None;
        }
        let mut process_id = 0;
        if GetWindowThreadProcessId(hwnd, &mut process_id) == 0 || process_id == 0 {
            return None;
        }
        let excluded = process_id == std::process::id()
            || hwnd == GetDesktopWindow()
            || hwnd == GetShellWindow()
            || IsWindowVisible(hwnd) == 0
            || IsIconic(hwnd) != 0
            || is_shell_class(hwnd)?;
        let result = if excluded {
            Some(FullscreenObservation {
                covered: false,
                monitor_rect,
            })
        } else {
            let mut cloaked = 0_u32;
            if DwmGetWindowAttribute(
                hwnd,
                DWMWA_CLOAKED as u32,
                (&mut cloaked as *mut u32).cast(),
                size_of::<u32>() as u32,
            ) < 0
            {
                return None;
            }
            if cloaked != 0 {
                Some(FullscreenObservation {
                    covered: false,
                    monitor_rect,
                })
            } else {
                let mut outer: RECT = zeroed();
                let mut frame: RECT = zeroed();
                if GetWindowRect(hwnd, &mut outer) == 0
                    || DwmGetWindowAttribute(
                        hwnd,
                        DWMWA_EXTENDED_FRAME_BOUNDS as u32,
                        (&mut frame as *mut RECT).cast(),
                        size_of::<RECT>() as u32,
                    ) < 0
                {
                    return None;
                }
                SetLastError(0);
                let style = GetWindowLongPtrW(hwnd, GWL_STYLE);
                if style == 0 && GetLastError() != 0 {
                    return None;
                }
                classify(WindowGeometry {
                    window_rect: physical(outer),
                    frame_rect: physical(frame),
                    monitor_rect,
                    maximized: IsZoomed(hwnd) != 0,
                    has_standard_frame: (style as u32 & WS_CAPTION) == WS_CAPTION
                        || (style as u32 & WS_THICKFRAME) != 0,
                })
            }
        };
        // A fast foreground switch can invalidate a coherent read without any
        // individual API failing. Its already-queued WinEvent requests a fresh
        // snapshot; never label the previous app's geometry as current.
        if GetForegroundWindow() == hwnd {
            result
        } else {
            None
        }
    }
}
